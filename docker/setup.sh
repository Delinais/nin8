#!/bin/sh
# Host-side helper for the Docker setup. Checks the pieces compose.yaml wires
# into the container (docker, X11/XWayland, PipeWire/PulseAudio, MIDI) and
# writes .env with your uid/gid. Safe to re-run; changes nothing but .env.
#
#   ./docker/setup.sh && docker compose up --build -d
#
# Run it as your normal desktop user, from a terminal inside the desktop session.
set -eu
cd "$(dirname "$0")/.."

problems=0
ok()   { printf '  [ok]   %s\n' "$*"; }
warn() { printf '  [warn] %s\n' "$*"; problems=$((problems + 1)); }
hint() { printf '         %s\n' "$*"; }

uid=$(id -u)
gid=$(id -g)

if [ "$uid" -eq 0 ]; then
    echo "Run this as your normal desktop user, not root/sudo: the container has to run as" >&2
    echo "your uid for PipeWire/PulseAudio and X11 access (and your session's environment" >&2
    echo "is what gets passed in)." >&2
    exit 1
fi

echo "Docker"
if ! command -v docker >/dev/null 2>&1; then
    warn "docker not found."
    hint "Arch/Garuda: sudo pacman -S docker docker-compose docker-buildx"
elif ! docker compose version >/dev/null 2>&1; then
    warn "the 'docker compose' plugin is missing."
    hint "Arch/Garuda: sudo pacman -S docker-compose docker-buildx"
elif ! docker info >/dev/null 2>&1; then
    warn "cannot talk to the Docker daemon."
    hint "Arch/Garuda: sudo systemctl enable --now docker.socket"
    hint "              sudo usermod -aG docker \"\$USER\"   (then log out and back in)"
else
    ok "docker + compose reachable"
fi

echo "Display"
if [ -z "${DISPLAY:-}" ]; then
    warn "DISPLAY is not set - run this from a terminal inside your desktop session."
else
    num="${DISPLAY#:}"
    num="${num%%.*}"
    if [ -S "/tmp/.X11-unix/X${num}" ]; then
        ok "X11 socket for DISPLAY=${DISPLAY}"
        if [ -n "${WAYLAND_DISPLAY:-}" ]; then
            hint "Wayland session: the app runs through XWayland (JUCE embeds its UI over X11)."
        fi
    else
        warn "no X11 socket /tmp/.X11-unix/X${num} for DISPLAY=${DISPLAY}"
    fi
fi
xauth="${XAUTHORITY:-$HOME/.Xauthority}"
if [ -r "$xauth" ]; then
    ok "X authority file $xauth"
else
    warn "X authority file $xauth is not readable (XAUTHORITY unset or stale?)"
    hint "On KDE Wayland it is /run/user/$uid/xauth_*; make sure XAUTHORITY is exported in this shell."
fi

echo "Audio"
runtime="${XDG_RUNTIME_DIR:-/run/user/$uid}"
if [ -S "$runtime/pulse/native" ]; then
    ok "PulseAudio protocol socket $runtime/pulse/native (PipeWire-pulse or PulseAudio)"
else
    warn "no $runtime/pulse/native - is pipewire-pulse (or pulseaudio) running?"
    hint "systemctl --user enable --now pipewire-pulse.socket"
fi

echo "MIDI (optional)"
midi=0
if [ -c /dev/snd/seq ]; then
    ok "/dev/snd/seq present - enabling hardware MIDI input"
    midi=1
else
    hint "no /dev/snd/seq (snd-seq kernel module not loaded). MIDI input stays off;"
    hint "re-run this script after plugging in a MIDI device or 'sudo modprobe snd-seq'."
fi

# --- .env -------------------------------------------------------------------
marker='# generated by docker/setup.sh'
tmp=$(mktemp)
{
    echo "$marker"
    echo "NIN8_UID=$uid"
    echo "NIN8_GID=$gid"
    if [ "$midi" -eq 1 ]; then
        audio_gid=$(getent group audio 2>/dev/null | cut -d: -f3 || true)
        if [ -n "$audio_gid" ]; then
            echo "AUDIO_GID=$audio_gid"
            echo "COMPOSE_FILE=compose.yaml:compose.midi.yaml"
        else
            echo "# no 'audio' group found - MIDI override not enabled" >&2
        fi
    fi
} >"$tmp"

echo ".env"
if [ -e .env ] && ! grep -qxF "$marker" .env; then
    warn ".env exists and was not generated by this script; leaving it alone. Wanted contents:"
    sed 's/^/         /' "$tmp"
    rm -f "$tmp"
else
    mv "$tmp" .env
    ok "wrote .env (uid=$uid gid=$gid)"
fi

echo
if [ "$problems" -eq 0 ]; then
    echo "All good:  docker compose up --build -d"
else
    echo "$problems warning(s) above - fix them, then:  docker compose up --build -d"
fi
